"""Generate the CLI's contract models and data copies from `packages/jobs-contracts`.

Usage (from `apps/jobs-cli`):

    uv run python scripts/gen_contracts.py           # regenerate in place
    uv run python scripts/gen_contracts.py --check   # fail when the committed files are stale

Outputs (all committed, never hand-edited):

- `src/pilih_jobs/contracts/_generated/<group>.py` — Pydantic v2 models generated with
  `datamodel-code-generator` from `packages/jobs-contracts/schema/<group>.json` (D-20,
  16 §1), plus `__init__.py` carrying `CONTRACTS_VERSION` and `SCHEMA_SHA256`.
- `src/pilih_jobs/contracts/_generated/index.json` — the route table, table → record names
  and schema → group map exported by `scripts/export-contract-index.ts` with Bun.
- `src/pilih_jobs/contracts/data/` — byte copies of `adapters.json`,
  `skills-dictionary.json` and `psl/public_suffix_list.dat`.

Everything is generated into a temporary directory first; `--check` compares that tree
with the committed one byte for byte, so it never touches the working tree.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CLI_ROOT = Path(__file__).resolve().parent.parent
REPO_ROOT = CLI_ROOT.parent.parent
CONTRACTS = REPO_ROOT / "packages" / "jobs-contracts"
SCHEMA_DIR = CONTRACTS / "schema"
PACKAGE_DIR = CLI_ROOT / "src" / "pilih_jobs" / "contracts"
GENERATED_DIR = PACKAGE_DIR / "_generated"
DATA_DIR = PACKAGE_DIR / "data"

DATA_COPIES = {
    "adapters.json": CONTRACTS / "adapters.json",
    "skills-dictionary.json": CONTRACTS / "skills-dictionary.json",
    "public_suffix_list.dat": CONTRACTS / "psl" / "public_suffix_list.dat",
}

# Fixed generator options: changing any of them changes every generated file.
CODEGEN_ARGS = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--disable-timestamp",
    "--target-python-version",
    "3.11",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-schema-description",
    "--use-field-description",
    "--field-constraints",
    "--use-double-quotes",
    "--enum-field-as-literal",
    "all",
    "--use-annotated",
    "--collapse-root-models",
    "--keep-model-order",
    "--formatters",
    "builtin",
    # Plain strings: the schemas carry their own patterns, and pydantic's URL/email
    # types would normalise values (a URL gains a trailing "/"), breaking round trips.
    "--type-mappings",
    "string+email=string",
    "string+uri=string",
    "string+starts_with=string",
]

HEADER = (
    "# Generated by apps/jobs-cli/scripts/gen_contracts.py from\n"
    "# packages/jobs-contracts/schema/{source}. DO NOT EDIT: change the Zod contract,\n"
    "# run `bun run build` in packages/jobs-contracts, then `bun run contracts` here.\n"
)


def _fail(message: str) -> None:
    print(f"gen_contracts: {message}", file=sys.stderr)
    raise SystemExit(1)


def _contracts_version() -> str:
    package = json.loads((CONTRACTS / "package.json").read_text(encoding="utf-8"))
    version = package.get("version")
    if not isinstance(version, str):
        _fail("packages/jobs-contracts/package.json has no version")
    return str(version)


def _schema_digest() -> str:
    digest = hashlib.sha256()
    for path in sorted(SCHEMA_DIR.glob("*.json")):
        digest.update(path.name.encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def _run_codegen(out_dir: Path) -> None:
    command = [
        sys.executable,
        "-m",
        "datamodel_code_generator",
        "--input",
        str(SCHEMA_DIR),
        "--output",
        str(out_dir),
        *CODEGEN_ARGS,
    ]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        _fail(f"datamodel-codegen failed:\n{result.stdout}\n{result.stderr}")


def _postprocess(out_dir: Path) -> None:
    for path in sorted(out_dir.glob("*.py")):
        if path.name == "__init__.py":
            continue
        text = path.read_text(encoding="utf-8")
        lines = text.splitlines(keepends=True)
        # Drop the generator's own banner ("# generated by datamodel-codegen: …").
        while lines and lines[0].startswith("#"):
            lines.pop(0)
        source = path.stem.replace("_", "-") + ".json"
        path.write_text(HEADER.format(source=source) + "".join(lines), encoding="utf-8")
    groups = sorted(p.stem for p in out_dir.glob("*.py") if p.name != "__init__.py")
    init = (
        HEADER.format(source="*.json")
        + '"""Pydantic v2 models of `packages/jobs-contracts` (one module per schema group)."""\n'
        + "\n"
        + f'CONTRACTS_VERSION = "{_contracts_version()}"\n'
        + f'SCHEMA_SHA256 = "{_schema_digest()}"\n'
        + f"GROUPS = {tuple(groups)!r}\n"
    )
    (out_dir / "__init__.py").write_text(init, encoding="utf-8")


def _export_index(out_dir: Path) -> None:
    bun = shutil.which("bun")
    if bun is None:
        _fail("bun is required to export the contract index (https://bun.sh)")
    result = subprocess.run(
        [str(bun), str(CLI_ROOT / "scripts" / "export-contract-index.ts")],
        capture_output=True,
        text=True,
        check=False,
        cwd=CLI_ROOT,
    )
    if result.returncode != 0:
        _fail(f"export-contract-index.ts failed:\n{result.stderr}")
    index = json.loads(result.stdout)
    (out_dir / "index.json").write_text(
        json.dumps(index, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def _build(tmp: Path) -> tuple[Path, Path]:
    generated = tmp / "_generated"
    data = tmp / "data"
    data.mkdir(parents=True)
    _run_codegen(generated)
    _postprocess(generated)
    _export_index(generated)
    for name, source in DATA_COPIES.items():
        shutil.copyfile(source, data / name)
    return generated, data


def _tree(root: Path) -> dict[str, bytes]:
    if not root.exists():
        return {}
    return {
        str(p.relative_to(root)): p.read_bytes()
        for p in sorted(root.rglob("*"))
        if p.is_file() and "__pycache__" not in p.parts
    }


def _diff(expected: Path, actual: Path) -> list[str]:
    want, have = _tree(expected), _tree(actual)
    problems = [f"missing: {name}" for name in sorted(set(want) - set(have))]
    problems += [f"unexpected: {name}" for name in sorted(set(have) - set(want))]
    problems += [
        f"stale: {name}" for name in sorted(set(want) & set(have)) if want[name] != have[name]
    ]
    return problems


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="verify the committed files instead of writing"
    )
    args = parser.parse_args()
    if not SCHEMA_DIR.is_dir():
        _fail(f"schema directory not found: {SCHEMA_DIR}")
    with tempfile.TemporaryDirectory(prefix="pilih-contracts-") as tmp_name:
        generated, data = _build(Path(tmp_name))
        if args.check:
            problems = [f"_generated/{p}" for p in _diff(generated, GENERATED_DIR)]
            problems += [f"data/{p}" for p in _diff(data, DATA_DIR)]
            if problems:
                _fail(
                    "contract files are stale; run `bun run contracts` in apps/jobs-cli:\n  "
                    + "\n  ".join(problems)
                )
            print("gen_contracts: generated models and data copies are up to date")
            return
        for target, source in ((GENERATED_DIR, generated), (DATA_DIR, data)):
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(source, target)
        written = [str(p.relative_to(CLI_ROOT)) for p in (GENERATED_DIR, DATA_DIR)]
        print(f"gen_contracts: wrote {' and '.join(written)}")


if __name__ == "__main__":
    main()

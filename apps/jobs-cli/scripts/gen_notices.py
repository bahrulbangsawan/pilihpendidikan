"""Regenerate THIRD_PARTY_NOTICES from the installed runtime dependency closure (22 §3).

Usage (from `apps/jobs-cli`, after `uv sync`):  uv run python scripts/gen_notices.py

Walks the `Requires-Dist` closure of the `pilih-jobs` distribution (extras included where
requested, environment markers evaluated for this machine) and lists every package with
its version, license and home page. Dev-only tools are not part of the closure.
"""

from __future__ import annotations

import re
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "THIRD_PARTY_NOTICES"
HEADER = """THIRD-PARTY SOFTWARE NOTICES — pilih-jobs

pilih-jobs (MIT) is distributed with, and depends at runtime on, the third-party packages
listed below. Each is the property of its respective authors and is used under its own
license; the license texts ship inside each package's distribution (`*.dist-info`).

Notable components:
- Scrapling (BSD-3-Clause) — https://github.com/D4Vinci/Scrapling — used only through
  `pilih_jobs.discovery.engine`; stealth/impersonation features are never imported.
- Playwright for Python (Apache-2.0) — https://github.com/microsoft/playwright-python —
  drives Chromium; Chromium itself is downloaded by `pilih-jobs browser install` and is
  covered by its own notices (https://www.chromium.org/Home/chromium-security/).
- patchright (Apache-2.0) — a transitive dependency of scrapling[fetchers]; never imported.

Generated by scripts/gen_notices.py from the installed dependency closure.

"""


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _license(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [
        c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "UNKNOWN"


def _homepage(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    if meta.get("Home-page"):
        return str(meta["Home-page"])
    for url in meta.get_all("Project-URL") or []:
        label, _, link = url.partition(",")
        if label.strip().lower() in ("homepage", "source", "repository", "source code"):
            return link.strip()
    return ""


def closure(root: str) -> list[metadata.Distribution]:
    env = default_environment()
    seen: dict[str, metadata.Distribution] = {}
    queue: list[tuple[str, frozenset[str]]] = [(root, frozenset())]
    while queue:
        name, extras = queue.pop()
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        key = _norm(dist.metadata["Name"])
        first_visit = key not in seen
        seen[key] = dist
        for raw in dist.requires or []:
            req = Requirement(raw)
            marker_ok = req.marker is None or any(
                req.marker.evaluate({**env, "extra": extra}) for extra in (extras or {""})
            )
            if marker_ok and (first_visit or req.extras):
                queue.append((req.name, frozenset(req.extras)))
    seen.pop(_norm(root), None)
    return sorted(seen.values(), key=lambda d: _norm(d.metadata["Name"]))


def main() -> None:
    lines = [HEADER]
    for dist in closure("pilih-jobs"):
        name, version = dist.metadata["Name"], dist.version
        lines.append(f"{name} {version}\n  License: {_license(dist)}\n")
        homepage = _homepage(dist)
        if homepage:
            lines.append(f"  Home: {homepage}\n")
        lines.append("\n")
    TARGET.write_text("".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

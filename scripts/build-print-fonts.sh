#!/usr/bin/env bash
# Builds the Inter cuts the three builders embed in their @react-pdf
# documents (DESIGN.md § Implementation › Print artifacts) and the table of
# characters they cover. Run it after upgrading @fontsource/inter:
#
#   bash scripts/build-print-fonts.sh
#
# Needs fontTools (`pip install fonttools`). For each weight it merges the
# @fontsource latin, latin-ext and vietnamese subsets into one font, so a
# word never spans two fonts (react-pdf would break it there, and set the
# hyphen or ellipsis it inserts in a cut that lacks it), and writes it as
# WOFF, the format fontkit reads, to packages/ui/src/print/fonts/. The
# generated files are committed; the apps never run this.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/packages/ui/src/print/fonts"
COVERAGE="$ROOT/packages/ui/src/print/print-coverage.ts"
SUBSETS=(latin latin-ext vietnamese)
WEIGHTS=(400 600 700)

# @fontsource/inter is a dependency of every builder; resolve it from one.
PKG="$(cd "$ROOT/apps/cv" && bun -e 'console.log(require.resolve("@fontsource/inter/package.json"))')"
FILES="$(dirname "$PKG")/files"

# The interpreter that has fontTools: its own CLI's, or python3.
PYTHON="python3"
if ! "$PYTHON" -c "import fontTools" 2>/dev/null; then
  CLI="$(command -v fonttools || true)"
  if [[ -n "$CLI" ]]; then
    PYTHON="$(head -1 "$CLI" | sed 's/^#!//')"
  fi
fi
"$PYTHON" -c "import fontTools" 2>/dev/null || {
  echo "fontTools not found: pip install fonttools" >&2
  exit 1
}

mkdir -p "$OUT"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for weight in "${WEIGHTS[@]}"; do
  inputs=()
  for subset in "${SUBSETS[@]}"; do
    inputs+=("$FILES/inter-$subset-$weight-normal.woff")
  done
  "$PYTHON" -m fontTools.merge --output-file="$TMP/inter-$weight.ttf" "${inputs[@]}"
done

"$PYTHON" - "$TMP" "$OUT" "$COVERAGE" "${WEIGHTS[@]}" <<'PY'
import sys
from fontTools.ttLib import TTFont

tmp, out, coverage, *weights = sys.argv[1:]
covered = None
for weight in weights:
    font = TTFont(f"{tmp}/inter-{weight}.ttf")
    points = set(font.getBestCmap())
    covered = points if covered is None else covered & points
    font.flavor = "woff"
    font.save(f"{out}/inter-print-{weight}.woff")

ranges = []
for point in sorted(covered):
    if ranges and point == ranges[-1][1] + 1:
        ranges[-1][1] = point
    else:
        ranges.append([point, point])

rows = ",\n".join(f"  [0x{a:04x}, 0x{b:04x}]" for a, b in ranges)
with open(coverage, "w") as handle:
    handle.write(
        "// Generated by scripts/build-print-fonts.sh from the merged Inter cuts\n"
        "// in ./fonts — do not edit. Every character all three weights have, as\n"
        "// inclusive [first, last] code point ranges.\n"
        f"export const PRINT_COVERAGE: readonly (readonly [number, number])[] = [\n{rows},\n];\n"
    )
print(f"{len(covered)} characters in {len(ranges)} ranges")
PY

cp "$(dirname "$PKG")/LICENSE" "$OUT/OFL.txt"
ls -l "$OUT"

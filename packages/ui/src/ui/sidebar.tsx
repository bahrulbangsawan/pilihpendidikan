// Loading rows. Skeletons are `pane`, so here they step up to `pane-2` to
// stay visible on the sidebar.
function SidebarMenuSkeleton({
  className,
  showIcon = false,
  ...props
}: React.ComponentProps<"div"> & {
  showIcon?: boolean;
}) {
  // A width between 50 and 90% so a stack of rows looks like text.
  const [width] = useState(() => `${Math.floor(Math.random() * 40) + 50}%`);

  return (
    <div
      className={cn("flex h-8 items-center gap-2 rounded-sm px-2", className)}
      data-sidebar="menu-skeleton"
      data-slot="sidebar-menu-skeleton"
      {...props}
    >
      {showIcon && (
        <Skeleton
          className="size-3.5 bg-sidebar-accent"
          data-sidebar="menu-skeleton-icon"
        />
      )}
      <Skeleton
        className="h-3 max-w-(--skeleton-width) flex-1 bg-sidebar-accent"
        data-sidebar="menu-skeleton-text"
        style={
          {
            "--skeleton-width": width,
          } as React.CSSProperties
        }
      />
    </div>
  );
}


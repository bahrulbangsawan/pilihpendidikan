// Compiles the vendored Public Suffix List (psl/public_suffix_list.dat) into
// the `src/psl-data.ts` module that Workers and browsers can import.
import { domainToASCII } from "node:url";

const BEGIN_ICANN = "// ===BEGIN ICANN DOMAINS===";
const END_ICANN = "// ===END ICANN DOMAINS===";
const BEGIN_PRIVATE = "// ===BEGIN PRIVATE DOMAINS===";
const END_PRIVATE = "// ===END PRIVATE DOMAINS===";
const VERSION_LINE = /^\/\/ VERSION: (\S+)/m;
const COMMIT_LINE = /^\/\/ COMMIT: (\S+)/m;
const RULE_TOKEN = /^\S+/;
const ASCII_RULE = /^[a-z0-9.-]+$/;

export interface CompiledPsl {
  commit: string;
  icann: string[];
  private: string[];
  version: string;
}

/**
 * Converts one rule to ASCII: the `!` / `*.` prefix is kept, the domain is
 * mapped with the WHATWG domain-to-ASCII algorithm (UTS #46 → punycode) and
 * cross-checked against WHATWG URL host parsing, which is what the runtime
 * applies to inputs.
 */
function asciiRule(rule: string): string {
  let prefix = "";
  let domain = rule;
  if (domain.startsWith("!")) {
    prefix = "!";
    domain = domain.slice(1);
  } else if (domain.startsWith("*.")) {
    prefix = "*.";
    domain = domain.slice(2);
  }
  const ascii = domainToASCII(domain);
  const viaUrl = new URL(`http://${domain}`).hostname;
  if (ascii === "" || ascii !== viaUrl || !ASCII_RULE.test(ascii)) {
    throw new Error(`PSL rule "${rule}" does not map to ASCII consistently`);
  }
  return `${prefix}${ascii}`;
}

export function compilePsl(dat: string): CompiledPsl {
  const version = VERSION_LINE.exec(dat)?.[1];
  const commit = COMMIT_LINE.exec(dat)?.[1];
  if (!(version && commit)) {
    throw new Error("PSL header lacks VERSION / COMMIT");
  }
  const icann: string[] = [];
  const privateRules: string[] = [];
  let section: "icann" | "private" | null = null;
  for (const rawLine of dat.split("\n")) {
    const line = rawLine.trim();
    if (line === BEGIN_ICANN) {
      section = "icann";
    } else if (line === BEGIN_PRIVATE) {
      section = "private";
    } else if (line === END_ICANN || line === END_PRIVATE) {
      section = null;
    } else if (section && line !== "" && !line.startsWith("//")) {
      // A rule is read up to the first whitespace (publicsuffix.org/list).
      const token = RULE_TOKEN.exec(line)?.[0] ?? "";
      (section === "icann" ? icann : privateRules).push(asciiRule(token));
    }
  }
  if (icann.length < 5000 || privateRules.length < 1000) {
    throw new Error("PSL sections look truncated");
  }
  return { version, commit, icann, private: privateRules };
}

export function pslModuleSource(psl: CompiledPsl): string {
  return [
    "// GENERATED by scripts/generate.ts from psl/public_suffix_list.dat. Do not",
    "// edit: run `bun run build` after updating the vendored list.",
    "// Rules are ASCII (punycode), space-separated, in file order; `*.` marks a",
    "// wildcard rule and `!` an exception rule (https://publicsuffix.org/list/).",
    "",
    `export const PSL_VERSION = ${JSON.stringify(psl.version)};`,
    `export const PSL_COMMIT = ${JSON.stringify(psl.commit)};`,
    `export const PSL_ICANN_RULES = ${JSON.stringify(psl.icann.join(" "))};`,
    `export const PSL_PRIVATE_RULES = ${JSON.stringify(psl.private.join(" "))};`,
    "",
  ].join("\n");
}

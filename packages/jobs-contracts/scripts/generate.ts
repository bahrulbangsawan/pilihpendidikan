// Generates every derived file of the package and, with --check, verifies
// the committed copies are fresh.
//
//   bun scripts/generate.ts --write   (bun run build)
//   bun scripts/generate.ts --check   (bun run check)
//
// Outputs: src/psl-data.ts, src/email-templates-data.ts, schema/*.json,
// adapters.json (config_schema fields), test-vectors/*.json and
// examples/*.json. Every output goes through the repository's Biome
// formatter, so the committed files are Biome-clean. --check writes the
// regenerated set into a temp directory and fails on any byte difference.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
  existsSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { compilePsl, pslModuleSource } from "./lib/psl";

const PKG = resolve(import.meta.dir, "..");
const REPO = resolve(PKG, "../..");
const BIOME = join(REPO, "node_modules", ".bin", "biome");
const mode = process.argv.includes("--check") ? "check" : "write";

const failures: string[] = [];

function fail(message: string): void {
  failures.push(message);
}

/** Formats `text` as if it were the package file `relPath`. */
function biomeFormat(relPath: string, text: string): string {
  const result = spawnSync(BIOME, ["format", `--stdin-file-path=${relPath}`], {
    cwd: PKG,
    input: text,
    encoding: "utf8",
  });
  if (result.status !== 0) {
    throw new Error(`biome format failed for ${relPath}: ${result.stderr}`);
  }
  return result.stdout;
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function sha256(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

const outputs = new Map<string, string>();

function emit(relPath: string, text: string): void {
  outputs.set(relPath, biomeFormat(relPath, text));
}

function writeOut(root: string, relPath: string, text: string): void {
  const target = join(root, relPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
}

// ---------------------------------------------------------------------------
// 1. Data modules for runtimes that cannot read files (Workers, browsers)
// ---------------------------------------------------------------------------

const pslDat = readFileSync(join(PKG, "psl", "public_suffix_list.dat"), "utf8");
const psl = compilePsl(pslDat);
emit("src/psl-data.ts", pslModuleSource(psl));

const templates = {
  en: readFileSync(join(PKG, "email-templates", "en.txt"), "utf8"),
  id: readFileSync(join(PKG, "email-templates", "id.txt"), "utf8"),
};
emit(
  "src/email-templates-data.ts",
  [
    "// GENERATED by scripts/generate.ts from email-templates/{en,id}.txt. Do not",
    "// edit: change the .txt templates and run `bun run build`.",
    "",
    `export const EMAIL_TEMPLATES = {\n  en: ${JSON.stringify(templates.en)},\n  id: ${JSON.stringify(templates.id)},\n} as const;`,
    "",
  ].join("\n")
);

if (mode === "write") {
  // Later steps import the package, so its data modules must be fresh first.
  for (const relPath of ["src/psl-data.ts", "src/email-templates-data.ts"]) {
    writeOut(PKG, relPath, outputs.get(relPath) ?? "");
  }
}

// ---------------------------------------------------------------------------
// 2. JSON Schema groups
// ---------------------------------------------------------------------------

const { buildAllSchemaGroups } = await import("../src/schema-export");
for (const [group, document] of Object.entries(buildAllSchemaGroups())) {
  emit(`schema/${group}.json`, json(document));
}

// ---------------------------------------------------------------------------
// 3. adapters.json: config_schema generated from the Zod config schemas
// ---------------------------------------------------------------------------

const { adapterConfigJsonSchema, isAdapterId } = await import(
  "../src/adapters"
);
const adaptersFile = JSON.parse(
  readFileSync(join(PKG, "adapters.json"), "utf8")
) as { adapters: Record<string, unknown>[] };
for (const entry of adaptersFile.adapters) {
  const id = String(entry.id);
  if (entry.status !== "excluded" && isAdapterId(id)) {
    entry.config_schema = adapterConfigJsonSchema(id);
  }
}
emit("adapters.json", json(adaptersFile));

// ---------------------------------------------------------------------------
// 4. Test vectors (hand-written expectations, verified here)
// ---------------------------------------------------------------------------

const fp = await import("../src/fingerprint");
const ids = await import("../src/ids");
const stage = await import("../src/stage");
const enums = await import("../src/enums");
const cases = await import("./vector-cases");

const fingerprintCases = cases.FINGERPRINT_CASES.map((c) => {
  const key = fp.fingerprintKey(c.input);
  if (key !== c.key) {
    fail(
      `fingerprint "${c.name}": expected key ${c.key}, implementation ${key}`
    );
  }
  return {
    name: c.name,
    input: c.input,
    key: c.key,
    fingerprint: `fp1:${sha256(c.key)}`,
  };
});
const normalizeCases = cases.NORMALIZE_TEXT_CASES.map((c) => {
  const out = fp.normalizeText(c.input);
  if (out !== c.output) {
    fail(
      `normalizeText(${JSON.stringify(c.input)}) = ${JSON.stringify(out)}, expected ${JSON.stringify(c.output)}`
    );
  }
  return c;
});
const contentHashCases = cases.CONTENT_HASH_CASES.map((c) => {
  const normalized = `${fp.normalizeText(c.title)}\n${fp.normalizeText(c.description)}`;
  return { ...c, normalized, content_hash: sha256(normalized) };
});
const dedupeCases = cases.DEDUPE_GROUP_CASES.map((c) => {
  const key = fp.dedupeGroupKey(c.input);
  if (key !== c.key) {
    fail(
      `dedupeGroupKey ${JSON.stringify(c.input)} = ${key}, expected ${c.key}`
    );
  }
  return { ...c, dedupe_group: c.key === null ? null : sha256(c.key) };
});
const legacyCases = cases.LEGACY_CASES.map((c) => {
  const key = fp.legacyFingerprintKey(c.user_id, c.legacy_id);
  if (key !== c.key) {
    fail(`legacy key ${key} != ${c.key}`);
  }
  return { ...c, fingerprint: `fp1:${sha256(c.key)}` };
});

emit(
  "test-vectors/fingerprint.json",
  json({
    version: 1,
    algorithm:
      "fp1 (03 §4.2); see src/fingerprint.ts for every normalization step",
    psl_version: psl.version,
    cases: fingerprintCases,
    normalize_text: normalizeCases,
    content_hash: contentHashCases,
    dedupe_group: dedupeCases,
    legacy: legacyCases,
  })
);

const urlCases = cases.CANONICAL_URL_CASES.map((c) => {
  const out = fp.canonicalUrl(c.input);
  if (out !== c.output) {
    fail(`canonicalUrl(${c.input}) = ${out}, expected ${c.output}`);
  }
  return c;
});
emit(
  "test-vectors/canonical-url.json",
  json({ version: 1, algorithm: "canonical_url (03 §4.2)", cases: urlCases })
);

const domainCases = cases.REGISTRABLE_DOMAIN_CASES.map((c) => {
  const options = { includePrivate: c.include_private ?? true };
  const registrable = fp.registrableDomain(c.input, options);
  const suffix = fp.publicSuffix(c.input, options);
  if (registrable !== c.registrable_domain || suffix !== c.public_suffix) {
    fail(
      `domain ${JSON.stringify(c.input)}: expected ${c.registrable_domain}/${c.public_suffix}, implementation ${registrable}/${suffix}`
    );
  }
  return {
    input: c.input,
    include_private: c.include_private ?? true,
    registrable_domain: c.registrable_domain,
    public_suffix: c.public_suffix,
  };
});
emit(
  "test-vectors/registrable-domain.json",
  json({
    version: 1,
    psl_version: psl.version,
    psl_commit: psl.commit,
    cases: domainCases,
  })
);

const legal = new Set(
  cases.LEGAL_STAGE_EDGES.flatMap(([from, to, actors]) =>
    actors.map((actor) => `${from}>${to}>${actor}`)
  )
);
const stageCases = enums.STAGES.flatMap((from) =>
  enums.STAGES.flatMap((to) =>
    enums.STAGE_ACTORS.map((actor) => {
      const allowed = legal.has(`${from}>${to}>${actor}`);
      if (stage.canTransition(from, to, actor) !== allowed) {
        fail(`canTransition(${from}, ${to}, ${actor}) should be ${allowed}`);
      }
      return { from, to, actor, allowed };
    })
  )
);
emit(
  "test-vectors/stage-transitions.json",
  json({
    version: 1,
    source: "03 §5.1 with the leaf-1.1 driver interpretation",
    actors: enums.STAGE_ACTORS,
    cases: stageCases,
  })
);

const timeCases = cases.ULID_TIME_CASES.map((c) => {
  const out = ids.encodeUlidTime(c.ms);
  if (
    out !== c.time ||
    ids.decodeUlidTime(`${out}${"0".repeat(16)}`) !== c.ms
  ) {
    fail(`ULID time ${c.ms} → ${out}, expected ${c.time}`);
  }
  return c;
});
const validityCases = cases.ID_VALIDITY_CASES.map((c) => {
  const valid = ids.isId(c.prefix as Parameters<typeof ids.isId>[0], c.value);
  if (valid !== c.valid) {
    fail(`isId(${c.prefix}, ${c.value}) should be ${c.valid}`);
  }
  return c;
});
emit(
  "test-vectors/ids.json",
  json({
    version: 1,
    alphabet: ids.CROCKFORD_ALPHABET,
    max_clock_skew_ms: ids.ID_MAX_CLOCK_SKEW_MS,
    ulid_time: timeCases,
    validity: validityCases,
  })
);

// ---------------------------------------------------------------------------
// 5. Example payloads (validated against their schemas)
// ---------------------------------------------------------------------------

const { RECORD_EXAMPLES, ROUTE_EXAMPLES } = await import("../test/examples");
const { TABLE_RECORDS } = await import("../src/records");
const { API_ROUTE_SCHEMAS } = await import("../src/api/routes");

for (const [table, schema] of Object.entries(TABLE_RECORDS)) {
  const example = (RECORD_EXAMPLES as Record<string, unknown>)[table];
  const parsed = schema.safeParse(example);
  if (!parsed.success) {
    fail(`example row for ${table} is invalid: ${parsed.error.message}`);
  }
}
for (const [key, contract] of Object.entries(API_ROUTE_SCHEMAS)) {
  const example = ROUTE_EXAMPLES[key];
  if (!example) {
    fail(`no example for route ${key}`);
    continue;
  }
  const checks: [
    string,
    (
      | { safeParse: (v: unknown) => { success: boolean; error?: unknown } }
      | null
      | undefined
    ),
    unknown,
  ][] = [
    ["response", contract.response, example.response],
    ["request", contract.request, example.request],
    ["query", "query" in contract ? contract.query : undefined, example.query],
  ];
  for (const [part, schema, value] of checks) {
    if (schema && value !== undefined) {
      const parsed = schema.safeParse(value);
      if (!parsed.success) {
        fail(`example ${part} of ${key} is invalid: ${String(parsed.error)}`);
      }
    }
  }
}
emit("examples/records.json", json(RECORD_EXAMPLES));
// The adapters example is the manifest regenerated above (the imported JSON
// module may predate this run).
emit(
  "examples/api.json",
  json({
    ...ROUTE_EXAMPLES,
    "GET /api/v1/sources/adapters": { response: adaptersFile },
  })
);

// ---------------------------------------------------------------------------
// Write or compare
// ---------------------------------------------------------------------------

if (failures.length > 0) {
  console.error(
    `generate: ${failures.length} problem(s):\n- ${failures.join("\n- ")}`
  );
  process.exit(1);
}

if (mode === "write") {
  for (const [relPath, text] of outputs) {
    writeOut(PKG, relPath, text);
  }
  console.log(`generate: wrote ${outputs.size} files`);
} else {
  const temp = mkdtempSync(join(tmpdir(), "jobs-contracts-"));
  const stale: string[] = [];
  try {
    for (const [relPath, text] of outputs) {
      writeOut(temp, relPath, text);
      const committed = join(PKG, relPath);
      const regenerated = readFileSync(join(temp, relPath), "utf8");
      if (
        !existsSync(committed) ||
        readFileSync(committed, "utf8") !== regenerated
      ) {
        stale.push(relPath);
      }
    }
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
  if (stale.length > 0) {
    console.error(
      `check: ${stale.length} generated file(s) are stale; run \`bun run build\`:\n- ${stale.join("\n- ")}`
    );
    process.exit(1);
  }
  console.log(`check: ${outputs.size} generated files are fresh`);
}
